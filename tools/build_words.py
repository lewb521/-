#!/usr/bin/env python3
"""由「英语词汇大纲」JSON 生成 words-data.js

用法：把 中考/高考/四级/六级/考研 五个 JSON 放到 ./vocabulary/ 下，然后
    python3 tools/build_words.py
输出：words-data.js（wordLists + zhTrans，供 index.html 直接引用）

词条字段：word / phonetic / pos / translation / levels / freq / collins / oxford
- 只保留能用虚拟键盘（a-z、连字符）拼出来的词
- 释义取首行中文，去掉 [医] [经] 这类领域标注与重复的词性前缀
- 每阶段按语料库词频从高到低排序，先学常用词
"""
import json, os, re, glob

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(BASE, 'vocabulary')
STAGES = ['中考', '高考', '四级', '六级', '考研']
TYPEABLE = re.compile(r'^[a-zA-Z-]+$')
POS_PREFIX = re.compile(r'^(?:[a-zA-Z]{1,6}\.\s*)+')
DOMAIN = re.compile(r'\[[^\]]{0,6}\]')

def clean_translation(text):
    """首行中文优先；若全是 [医] [计] 这类领域释义，则退而保留清洗后的内容。"""
    primary, fallback = [], []
    for line in (text or '').split('\n'):
        line = line.strip()
        if not line:
            continue
        line = POS_PREFIX.sub('', line).strip()
        cleaned = DOMAIN.sub('', line).strip(' ,;；')
        if not cleaned:
            continue
        fallback.append(cleaned)
        if not line.startswith('['):
            primary.append(cleaned)
    return '；'.join(primary or fallback)

def main():
    word_lists, trans = {}, {}
    for stage in STAGES:
        path = os.path.join(SRC, stage + '词汇.json')
        if not os.path.exists(path):
            raise SystemExit('缺少词库文件：' + path)
        data = json.load(open(path, encoding='utf-8-sig'))
        words = [w for w in data['words'] if TYPEABLE.match(w['word'])]
        words.sort(key=lambda w: min((w.get('freq') or {}).get('bnc') or 10**9,
                                     (w.get('freq') or {}).get('frq') or 10**9))
        word_lists[stage] = [w['word'] for w in words]
        for w in words:
            zh = clean_translation(w.get('translation', ''))
            pos = (w.get('pos') or '').strip()
            trans[w['word']] = ((pos + ' ') if pos else '') + zh
    out = ['// 不白背 - 词汇库（由「英语词汇大纲」生成，数据源 ECDICT，MIT）',
           '// Auto-generated by tools/build_words.py, do not edit',
           'const wordLists=' + json.dumps(word_lists, ensure_ascii=False, separators=(',', ':')) + ';',
           'const zhTrans=' + json.dumps(trans, ensure_ascii=False, separators=(',', ':')) + ';']
    open(os.path.join(BASE, 'words-data.js'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(' '.join('%s %d' % (s, len(word_lists[s])) for s in STAGES),
          '| 合计', sum(len(v) for v in word_lists.values()))

if __name__ == '__main__':
    main()
